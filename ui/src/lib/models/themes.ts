import type { ThemeId } from '../game/worlds'

export type BorderKind = 'rocks' | 'pillars' | 'crystals' | 'clouds' | 'balls' | 'dunes'
export type PlantKind = 'cactus' | 'fern' | 'post' | 'crystal' | 'palm' | 'ball' | 'tuft'

/** The colours and kinds of cover that give a world its look (no image files). */
export interface ArenaTheme {
  /** The two tile colours of the ground, and the floor that reaches out to the border. */
  tiles: [string, string]
  floor: string
  border: BorderKind
  borderColors: string[]
  wallSide: string
  wallTop: string
  /** A spike or dome on top of the walls, as well as the flat top. */
  wallCap: 'flat' | 'spikes' | 'dome'
  plant: PlantKind
  plantColors: string[]
  /** The ground under a patch of plants. */
  patch: string
  /** Colours of the props that lie around. */
  crate: string
  barrel: string
  rock: string
  skulls: boolean
  /** Glow colour for neon and lava looks. */
  glow?: string
  /** The sky behind the arena: top and bottom of a gradient. */
  sky: [string, string]
}

